// Copies the desktop app's 3D hero (renderer/js/hero3d.js) into the site, so the landing page
// renders exactly the same router scene as the app.
//
//   npm run sync          copy the app's file into src/vendor/hero3d.js
//   npm run sync:check    exit 1 if the vendored copy has drifted from the app
//
// The vendored copy is committed, so a site build never depends on the app's folder.

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const siteRoot = resolve(here, '..');
const source = resolve(siteRoot, '..', 'renderer', 'js', 'hero3d.js');
const target = resolve(siteRoot, 'src', 'vendor', 'hero3d.js');

const BANNER =
  '// GENERATED by site/scripts/sync-hero.mjs from renderer/js/hero3d.js. Do not edit here:\n' +
  '// change the app file and run `npm run sync` in site/.\n';

const check = process.argv.includes('--check');

let src;
try {
  src = await readFile(source, 'utf8');
} catch (err) {
  console.error(`sync-hero: cannot read ${source}: ${err.message}`);
  process.exit(1);
}

const next = BANNER + src.replace(/\r\n/g, '\n');

if (check) {
  let current = '';
  try {
    current = (await readFile(target, 'utf8')).replace(/\r\n/g, '\n');
  } catch {
    /* missing counts as drift */
  }
  if (current !== next) {
    console.error('sync-hero: src/vendor/hero3d.js is out of date. Run `npm run sync`.');
    process.exit(1);
  }
  console.log('sync-hero: vendored hero is up to date.');
} else {
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, next, 'utf8');
  console.log(`sync-hero: ${relative(siteRoot, source)} -> ${relative(siteRoot, target)} (${next.length} bytes)`);
}
