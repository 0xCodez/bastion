// Vendor name for a MAC, or null when unknown or randomized.
function vendorFor(mac) {
  const m = normalizeMac(mac);
  if (!m) return null;
  if (isRandomizedMac(m)) return null;
  return MAP.get(m.replace(/:/g, '').slice(0, 6).toUpperCase()) || null;
}

